#!/usr/bin/env node
/**
 * Generate one service worker per built game, so the games actually work offline.
 *
 * Measured before writing this (scripts/offline-status.json): a built game reloaded
 * with the network denied showed Chrome's ERR_INTERNET_DISCONNECTED page and no
 * game object, because nothing cached anything. Every request was already
 * same-origin - self-hosting was never the problem, caching was.
 *
 * Generated at build time rather than hand-written per package for two reasons.
 * The precache list has to name the HASHED bundle file names, which only exist
 * after the build; and five hand-maintained copies would drift.
 *
 * Strategy, chosen to match how these games load:
 *   - Precache on install: index.html plus everything index.html references
 *     (the JS chunks, the fonts). That is the set that must be present for the
 *     game to boot at all, so it is fetched up front.
 *   - Runtime cache, cache-first, for everything else same-origin under scope:
 *     Phaser fetches sprites and audio from its loader during play, and there are
 *     171 of those across the games. Precaching all of it would make the first
 *     visit pay for assets a player might never reach.
 *   - Navigation requests fall back to the cached index.html, so a reload with no
 *     network still boots instead of showing the browser's error page.
 *
 * Paths are stored RELATIVE to the worker's own scope. The built HTML references
 * assets by an absolute deploy path (/open-games/<slug>/assets/...), which is not
 * where the files sit on disk and would not resolve if the site were mounted
 * somewhere else; resolving against the worker's location keeps the worker correct
 * under any base path.
 */
import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from 'node:fs';
import { join, basename, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const ROOT = join(fileURLToPath(new URL('.', import.meta.url)), '..');

function walk(dir, out = []) {
  if (!existsSync(dir)) return out;
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walk(full, out);
    else out.push(full);
  }
  return out;
}

/** Files the page needs, as scope-relative paths: tag references plus CSS url(). */
function coldLoadSet(dist) {
  const indexPath = join(dist, 'index.html');
  if (!existsSync(indexPath)) return null;
  const html = readFileSync(indexPath, 'utf8');
  const all = walk(dist);
  const set = new Set(['./']); // the navigation itself

  const addByName = (ref) => {
    if (!ref || ref.startsWith('data:') || /^[a-z]+:\/\//i.test(ref)) return;
    // Match by file NAME: the built paths are absolute to a deploy base that does
    // not exist on disk, so resolving them literally would find nothing.
    const name = basename(ref.split('?')[0].split('#')[0]);
    for (const f of all) {
      if (basename(f) === name) set.add(`./${relative(dist, f).split('\\').join('/')}`);
    }
  };

  for (const m of html.matchAll(/(?:src|href)\s*=\s*"([^"]+)"/g)) addByName(m[1]);

  // Also take url() out of inline and linked CSS. A font declared in @font-face is
  // needed OFFLINE even when it is deliberately not preloaded: champs stopped
  // preloading its two 540 KB Korean weights because that made a metered player wait
  // 1.09 MB before the game itself, but the worker installs in the BACKGROUND after
  // load, so precaching them there costs nothing at startup and is what keeps
  // offline text from falling back to a system face.
  for (const m of html.matchAll(/url\(\s*['"]?([^'")]+)['"]?\s*\)/g)) addByName(m[1]);
  for (const file of all) {
    if (!file.endsWith('.css')) continue;
    for (const m of readFileSync(file, 'utf8').matchAll(/url\(\s*['"]?([^'")]+)['"]?\s*\)/g)) {
      addByName(m[1]);
    }
  }

  return [...set];
}

const WORKER = (cacheName, precache) => `/**
 * GENERATED by scripts/gen-service-worker.mjs - do not edit.
 *
 * Exists so the game keeps working when the network does not. See
 * scripts/offline-status.json for the measurement that motivated it.
 */
const CACHE = ${JSON.stringify(cacheName)};
const PRECACHE = ${JSON.stringify(precache, null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(CACHE);
      // addAll is atomic: one missing file would fail the whole install and leave
      // the game with no worker at all, so each is added individually and a
      // failure is reported rather than fatal.
      await Promise.all(
        PRECACHE.map(async (url) => {
          try {
            await cache.add(new Request(url, { cache: 'reload' }));
          } catch (err) {
            console.warn('[sw] precache miss', url, err);
          }
        }),
      );
      await self.skipWaiting();
    })(),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      // Drop caches from earlier builds, or a deploy would serve a stale bundle
      // forever: the name carries a content hash, so anything else is old.
      const names = await caches.keys();
      await Promise.all(names.filter((n) => n !== CACHE && n.startsWith('open-games:')).map((n) => caches.delete(n)));
      await self.clients.claim();
    })(),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  // Only ever serve this game's own scope. Anything else is left alone - the
  // project makes zero third-party requests and a worker should not become the
  // place that changes.
  if (url.origin !== self.location.origin) return;
  if (!url.pathname.startsWith(new URL('./', self.location.href).pathname)) return;

  event.respondWith(
    (async () => {
      const cache = await caches.open(CACHE);

      // A reload with no network must boot the game, not the browser's error page.
      if (request.mode === 'navigate') {
        const cached = await cache.match('./');
        if (cached) {
          try {
            const fresh = await fetch(request);
            cache.put('./', fresh.clone());
            return fresh;
          } catch {
            return cached;
          }
        }
      }

      const hit = await cache.match(request, { ignoreSearch: true });
      if (hit) return hit;

      try {
        const response = await fetch(request);
        // Cache successful same-origin responses as they are first used, so the
        // sprites and audio a player actually reaches survive going offline.
        if (response && response.status === 200 && response.type === 'basic') {
          cache.put(request, response.clone());
        }
        return response;
      } catch (err) {
        const stale = await cache.match(request, { ignoreSearch: true });
        if (stale) return stale;
        throw err;
      }
    })(),
  );
});
`;

const REGISTRATION = `<script>
// Registers the generated service worker so the game survives losing the network.
// Guarded deliberately: a file:// open and any non-secure context have no worker
// support, and the game must still run there rather than throwing on load.
if ('serviceWorker' in navigator && (location.protocol === 'https:' || location.hostname === 'localhost' || location.hostname === '127.0.0.1')) {
  window.addEventListener('load', function () {
    navigator.serviceWorker.register('./sw.js').catch(function (err) {
      console.warn('[sw] registration failed', err);
    });
  });
}
</script>`;

const slugs = readdirSync(join(ROOT, 'packages')).filter((p) =>
  existsSync(join(ROOT, 'packages', p, 'dist', 'index.html')),
);

if (slugs.length === 0) {
  console.error('gen-service-worker found no built games. Run `npm run build:games` first.');
  process.exit(2);
}

for (const slug of slugs) {
  const dist = join(ROOT, 'packages', slug, 'dist');
  const precache = coldLoadSet(dist);

  // Cache name carries a hash of the precache list, so a new build gets a new
  // cache and the activate handler can delete the old one.
  const hash = createHash('sha256').update(precache.join('\n')).digest('hex').slice(0, 12);
  const cacheName = `open-games:${slug}:${hash}`;

  writeFileSync(join(dist, 'sw.js'), WORKER(cacheName, precache));

  const indexPath = join(dist, 'index.html');
  let html = readFileSync(indexPath, 'utf8');
  if (!html.includes("serviceWorker' in navigator")) {
    html = html.replace('</body>', `${REGISTRATION}\n</body>`);
    if (!html.includes("serviceWorker' in navigator")) html += REGISTRATION; // no </body>
    writeFileSync(indexPath, html);
  }

  console.log(`  ${slug.padEnd(9)} sw.js written, ${precache.length} file(s) precached`);
}

console.log(`gen-service-worker: ${slugs.length} game(s) made offline-capable.`);
